export const biomeForSeed = (seed: number): BiomeId => BIOMES[(seed >>> 0) % BIOMES.length].id;

function segmentDistance(x: number, y: number, a: Point, b: Point): number {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const t = Math.max(0, Math.min(1, ((x - a[0]) * dx + (y - a[1]) * dy) / (dx * dx + dy * dy || 1)));
  return Math.hypot(x - a[0] - dx * t, y - a[1] - dy * t);
}

export function outlineDistance(x: number, y: number, outline: Outline): number {
  let inside = false, distance = Infinity;
  for (let i = 0, j = outline.length - 1; i < outline.length; j = i++) {
    const a = outline[j], b = outline[i];
    if ((a[1] > y) !== (b[1] > y) && x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0]) inside = !inside;
    distance = Math.min(distance, segmentDistance(x, y, a, b));
  }
  return inside ? -distance : distance;
}

export function ridgeDistance(x: number, y: number, biome: BiomeTemplate): number {
  let distance = Infinity;
  for (const ridge of biome.ridges) for (let i = 1; i < ridge.points.length; i++) {
    distance = Math.min(distance, segmentDistance(x, y, ridge.points[i - 1], ridge.points[i]) - ridge.width);
  }
  return distance;
}
