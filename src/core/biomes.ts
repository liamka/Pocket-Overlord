const ridge = (width: number, ...points: Point[]): Ridge => ({ width, points });
const mirror = (points: Outline): Outline => points.map(([x, y]) => [100 - x, y]);
const oval = (x: number, y: number, rx: number, ry: number): Outline => Array.from({ length: 20 }, (_, i) => {
  const angle = i / 20 * Math.PI * 2;
  return [x + Math.cos(angle) * rx, y + Math.sin(angle) * ry];
});
const ring = (width: number, x: number, y: number, rx: number, ry: number): Ridge => {
  const points = oval(x, y, rx, ry);
  return ridge(width, ...points, points[0]);
};
const arc = (x: number, y: number, radius: number, start: number, end: number, steps: number): Outline =>
  Array.from({ length: steps + 1 }, (_, i) => {
    const angle = start + (end - start) * i / steps;
    return [x + Math.cos(angle) * radius, y + Math.sin(angle) * radius];
  });
