// A second contour inside each shell plate gives it a raised, layered surface.
const shellPlate = (points: Outline): readonly Ridge[] => {
  const cx = points.reduce((sum, point) => sum + point[0], 0) / points.length;
  const cy = points.reduce((sum, point) => sum + point[1], 0) / points.length;
  const inner: Outline = points.map(([x, y]) => [cx + (x - cx) * 0.57, cy + (y - cy) * 0.57]);
  return [ridge(0.32, ...points, points[0]), ridge(0.13, ...inner, inner[0])];
};

