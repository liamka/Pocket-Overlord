type TaperedPath = readonly (readonly [x: number, y: number, halfWidth: number])[];
const pathNormal = (path: TaperedPath, i: number): Point => {
  const a = path[Math.max(0, i - 1)], b = path[Math.min(path.length - 1, i + 1)];
  const length = Math.hypot(b[0] - a[0], b[1] - a[1]);
  return [-(b[1] - a[1]) / length, (b[0] - a[0]) / length];
};
// Authored centerlines keep the curling arms wide at the body and pointed at their tips.
const taperedLand = (path: TaperedPath): Outline => {
  const edge = (side: number): Point[] => path.map(([x, y, width], i) => {
    const [nx, ny] = pathNormal(path, i);
    return [x + nx * width * side, y + ny * width * side];
  });
  return [...edge(1), ...edge(-1).reverse()];
};
